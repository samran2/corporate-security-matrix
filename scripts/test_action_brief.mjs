import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";

const root = new URL("../", import.meta.url);
const files = ["matrix-domains.js", "matrix-actors.js", "matrix-briefs.js", "matrix-references.js", "matrix-overlays.js", "matrix-tools-d01-d03.js", "matrix-tools-d04-d06.js", "matrix-tools-d07-d09.js", "matrix-tools.js"];
const data = files.map((file) => fs.readFileSync(new URL(file, root), "utf8")).join("\n");
const app = fs.readFileSync(new URL("app.js", root), "utf8");
const marker = "\ntry {\n  const bootstrapError = validateBootstrapData();";
assert(app.includes(marker));
const context = { URL, document: { documentElement: { classList: { remove() {} } } } };
context.window = context;
vm.createContext(context);
vm.runInContext(`${data}\n${app.slice(0, app.indexOf(marker))}\nglobalThis.api = { createActionCatalog, createActionBriefModel, buildActionBriefMarkdown, getMatrixEntrySearchMatch };`, context);
const { createActionCatalog, createActionBriefModel, buildActionBriefMarkdown, getMatrixEntrySearchMatch } = context.api;
const catalog = createActionCatalog();
assert.equal(catalog.size, 180, "All 180 reviewed canonical controls are selectable.");
const ids = [...catalog.keys()];
const model = createActionBriefModel(catalog);
assert.equal(model.add("not-an-entry"), "unknown");
assert.equal(model.getItems().length, 0);
assert.equal(model.add(ids[0]), "added");
assert.equal(model.add(ids[0]), "duplicate", "Adding a duplicate is idempotent.");
assert.equal(model.getItems()[0].owner, "");
assert.equal(model.getItems()[0].horizon, "next");
assert.equal(model.update(ids[0], { owner: "A person's name" }), false);
assert.equal(model.update(ids[0], { horizon: "critical" }), false);
const owner = catalog.get(ids[0]).owners[0];
assert.equal(model.update(ids[0], { owner, horizon: "now" }), true);
assert.equal(model.getItems()[0].owner, owner);
assert.equal(model.getItems()[0].horizon, "now");
assert.equal(model.update(ids[0], { owner: "", horizon: "critical" }), false, "Invalid multi-field edits are rejected atomically.");
assert.equal(model.getItems()[0].owner, owner);
assert.equal(model.update(ids[0], { owner, notes: "private text" }), false, "Unknown document fields cannot enter the brief.");
assert.equal(model.update(ids[0], { horizon: "toString" }), false, "Prototype properties are not valid planning horizons.");
assert.equal(model.update(ids[0], { owner: "", horizon: "later" }), true);
assert.equal(model.update("not-an-entry", { horizon: "now" }), false);
for (const id of ids.slice(1, 12)) assert.equal(model.add(id), "added");
assert.equal(model.add(ids[12]), "limit");
assert.equal(model.getItems().length, 12);
assert.equal(model.remove(ids[0]), true);
assert.equal(model.remove(ids[0]), false);
assert.equal(model.add(ids[12]), "added");
model.clear();
assert.equal(model.getItems().length, 0);
const crossDomainIds = [ids[0], ids[80], ids[179]];
crossDomainIds.forEach((id) => model.add(id));
for (const item of model.getItems()) {
  assert.equal(item.tools.length, 2);
  assert(item.sources.length > 0);
  assert.equal(item.domainId, catalog.get(item.id).domainId);
  assert.equal(item.sources[0].id, catalog.get(item.id).sources[0].id);
}
assert.equal(model.update(crossDomainIds[1], { owner: catalog.get(crossDomainIds[0]).owners[0] }), false, "A role from another domain is not silently assigned.");
const leaked = model.getItems();
leaked[0].owner = "changed";
leaked[0].tools[0].name = "changed";
assert.equal(model.getItems()[0].owner, "");
assert.notEqual(model.getItems()[0].tools[0].name, "changed");
const markdown = buildActionBriefMarkdown(model.getItems());
assert.match(markdown, /1\.1\.0-candidate/);
assert.match(markdown, /Overlay: not included/);
assert.match(markdown, /Context sources, not entry-level proof/);
assert.match(markdown, /unencrypted/i);
for (const id of crossDomainIds) assert(markdown.includes(id));
const fixture = model.getItems()[0];
const escaped = buildActionBriefMarkdown([{ ...fixture, text: "[click](https://bad.example)\n# forged", tools: [], sources: [] }]);
assert(!escaped.includes("[click](https://bad.example)"), "Canonical prose remains prose in Markdown exports.");
assert(!escaped.includes("\n# forged"));
assert.equal(getMatrixEntrySearchMatch(ids[0].toLowerCase(), [ids[0]], []).matches, true);
assert.match(app, /const coreSearchValues = \[entry\.id,/, "Canonical entry IDs are searchable.");
assert.match(app, /state\.phase = validPhases\.has\(params\.get\("phase"\)\)/, "Back/Forward restores phase state with a safe fallback.");
assert.match(app, /function setPhase\(/);
assert.match(app, /phaseButtons\.forEach/);
assert(app.includes('querySelectorAll("button[data-phase-mode]")'), "Phase controls do not accidentally include the rendered matrix grid.");
assert.match(app, /window\.addEventListener\("afterprint",/);
assert(!/localStorage|sessionStorage|indexedDB|\bfetch\s*\(|XMLHttpRequest|WebSocket/.test(app), "Brief selections never enter persistence or the network.");
console.log("Action brief: canonical catalog, bounds, role/horizon validation, isolation, cross-domain context, Markdown safety and phase/ID contracts passed.");
